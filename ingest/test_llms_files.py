    def test_full_file_restores_text_that_ingest_escaped_as_prose(self):
        # MDX has no indented code, and ingest escapes braces in code spans that cross lines
        # like prose, so llms-full.txt undoes those escapes too and gets the source text back.
        source = (
            "Set {name} here.\n\n"
            "    an indented {line} is a paragraph in MDX\n\n"
            "A `multi-line\ncode {span}` example.\n\n"
            "```yaml\nkey: {value}\n```\n"
        )
        escaped = ingest._escape_mdx_braces(source)
        self.assertNotEqual(escaped, source)
        self.assertEqual(llms_files.llms_full_text(escaped), source)

    def test_index_skips_integration_pages_marked_outside_the_message(self):
        # Ingest treats any file containing the marker as a generated integration page.
        (self.docs / "Collecting Metrics/Collectors/Nginx.mdx").write_text(
            doc("/collecting-metrics/collectors/nginx", "Nginx", 20)
            + "\n<!-- DO NOT EDIT THIS FILE DIRECTLY, IT IS GENERATED BY THE COLLECTOR'S "
            "metadata.yaml FILE -->\n"
        )
        index, _ = llms_files.build_llms_files(self.docs)
        self.assertNotIn("/docs/collecting-metrics/collectors/nginx", index)
        self.assertEqual(llms_files.GENERATED_INTEGRATION_MARKER, ingest.INTEGRATION_MARKER)

    def test_missing_product_description_leaves_the_files_alone(self):
        (self.docs / "Welcome to Netdata/Complete Product Description.mdx").unlink()
        self.assertIsNone(llms_files.build_llms_files(self.docs))


