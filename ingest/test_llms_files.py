    def test_full_file_is_the_product_description_as_plain_markdown(self):
        _, full = llms_files.build_llms_files(self.docs)
        self.assertTrue(full.startswith("# Netdata: Complete Product Description\n"))
        self.assertNotIn("custom_edit_url", full)
        self.assertIn("Uses <5% CPU", full)
        self.assertIn(
            "[scalability](https://learn.netdata.cloud/docs/welcome-to-netdata/scalability#limits)",
            full,
        )
        self.assertIn("[pricing](https://www.netdata.cloud/pricing/)", full)
        self.assertIn('<a href="https://learn.netdata.cloud/docs/x">', full)
        self.assertIn("Inline `\\{kept\\}`", full)
        self.assertIn("template: \\{kept\\}\nlink: /docs/not-a-link\n", full)
        self.assertTrue(full.endswith("```\n"))

