def front_matter(**fields):
    lines = ["---"]
    for key, value in fields.items():
        if value is True:
            lines.append(f"{key}: true")
        elif value is None:
            lines.append(f"{key}: null")
        else:
            lines.append(f'{key}: "{value}"')
    lines.append("---")
    return "\n".join(lines) + "\n\n"


def doc(slug, label, position, description=None, **extra):
    fields = {
        "custom_edit_url": f"https://github.com/netdata/netdata/edit/master/docs{slug}.md",
        "sidebar_label": label,
        "learn_status": "Published",
        "sidebar_position": position,
        "learn_link": f"https://learn.netdata.cloud/docs{slug}",
        "slug": slug,
    }
    if description:
        fields["description"] = description
    fields.update(extra)
    return front_matter(**fields) + f"# {label}\n"


